# -*- coding: utf-8 -*-
"""S1 等价护栏：站点策略「阶段覆盖」静态检查（只读，不 import 爬虫.py、不发请求）。

两侧对比
--------
- 代码侧 `A` = `规则内核.扫描阶段清单()`：源码里所有 `_站点策略()/适配器策略()` 调用的**阶段字面量**；
- 适配器侧 `B` = `规则内核.导出适配器IR()`：每个适配器**声明实现**的阶段。

两类偏差（含义完全不同，别混为一谈）
------------------------------------
① **适配器声明了代码里不存在的阶段** ⇒ 真缺陷：阶段名拼写漂移，或代码已删该阶段。
   本脚本对它计数；`--严格` 时以退出码 1 报告（可挂门禁）。
② 代码里有、但**没有任何适配器声明** ⇒ **正常**：该阶段由通用规则承接
   （站点脱钩机制的设计就是"不声明就走通用路径"），只作信息展示。

为什么要它
----------
S1 要把规则内核抽成 IR 并拆分 `爬虫.py`。拆之前先得能回答"阶段名字两侧是否对齐"，
否则改名/搬代码时漏一处，症状是**某个站点某个阶段悄悄走回通用规则**（静默降级），
线上极难发现 —— 这个检查把它变成静态可查。

用法（项目根目录）
------------------
    .runtime\\python314\\python.exe 脚本\\检查阶段覆盖.py           # 信息模式，恒 0
    .runtime\\python314\\python.exe 脚本\\检查阶段覆盖.py --严格    # 有 ① 类偏差则 1
"""
import pathlib
import sys

_ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT / '源码'))

import 规则内核  # noqa: E402


def 检查(适配器表=None) -> dict:
    """跑一次双侧对比，返回结构化结果（纯函数，便于单测）。"""
    阶段表 = 规则内核.扫描阶段清单()
    适配器IR = 规则内核.导出适配器IR(适配器表)
    已知阶段 = set(阶段表)
    未知 = []
    声明过 = set()
    for 名称, 信息 in sorted(适配器IR.items()):
        for 阶段 in 信息.get('声明阶段') or []:
            声明过.add(阶段)
            if 阶段 not in 已知阶段:
                未知.append({'适配器': 名称, '阶段': 阶段})
    return {
        '阶段总数': len(已知阶段),
        '适配器数': len(适配器IR),
        '有声明阶段的适配器数': sum(1 for v in 适配器IR.values() if v.get('声明阶段')),
        '未声明阶段': sorted(已知阶段 - 声明过),
        '未知阶段': 未知,
    }


def 打印结果(结果: dict) -> None:
    print(f"阶段总数 {结果['阶段总数']} / 适配器 {结果['适配器数']}"
          f"（其中 {结果['有声明阶段的适配器数']} 个声明了自己的阶段）")
    if 结果['未知阶段']:
        print(f"\n[!] 适配器声明了代码里不存在的阶段（{len(结果['未知阶段'])} 处，疑似拼写漂移）:")
        for 项 in 结果['未知阶段']:
            print(f"    {项['适配器']} -> {项['阶段']}")
    else:
        print('\n[OK] 所有适配器声明的阶段都在代码里存在')
    if 结果['未声明阶段']:
        print(f"\n[i] 无任何适配器声明的阶段（{len(结果['未声明阶段'])} 个，由通用规则承接，正常）:")
        print('    ' + '、'.join(结果['未声明阶段']))


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    严格 = '--严格' in argv
    结果 = 检查()
    打印结果(结果)
    if 严格 and 结果['未知阶段']:
        print(f"\n--- 严格模式: 发现 {len(结果['未知阶段'])} 处未知阶段，请修复后再打包！")
        return 1
    print('\n--- 阶段覆盖检查通过。')
    return 0


if __name__ == '__main__':
    sys.exit(main())
