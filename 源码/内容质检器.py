# -*- coding: utf-8 -*-
"""章节内容语义质检器
====================

对清洗后的章节正文做多维度量化评分, 判断内容是否完整且具备语义
价值, 过滤无意义字符、乱码或空白噪声数据。

评分维度与权重:
  - 有效长度 (25): 净字符数 ≥ 500 (短章 ≥ 200)
  - 中文占比 (25): CJK 字符 / 总字符 ≥ 60%
  - 乱码率   (20): 替换符及连续异常符号串占比 ≤ 5%
  - 重复率   (15): 行级去重后/去重前行数, 重复行 ≤ 40%
  - 标点密度 (15): 中英标点/总字符 在 2%-25% 区间

判定: 总分 ≥ 60 且无单项硬伤 (乱码率 > 30% 或中文占比 < 30%)
       → 有效=True, 否则视为质检失败。

设计原则: 纯文本统计, 无第三方依赖, 通用适用于任何站点。
"""

import re
from dataclasses import dataclass, field
from typing import List, Dict

# ---- Rust 加速 (可选): 缺失时自动回退纯 Python, 不影响任何功能 ----
try:
    from rust_core import qa_质检_full_nogil as _rs_质检_full
    _RUST_质检可用 = True
except (ImportError, OSError):
    _RUST_质检可用 = False

# ---- 评分参数 (集中定义, 便于调整) ----
# ⚠ 双实现同步警告: 本组权重/阈值在 rust_core_poc/pyo3_ext/src/lib.rs
#   (W_长度 / 阈值长 等常量) 有一份 Rust 镜像。存在 源码/rust_core.pyd 时
#   质检走 Rust 路径, 只改这里不会生效 — 调参必须两边同步修改, 并运行
#   `python rust_core_poc/qa_parity.py` 验证逐字段一致。
权重_长度 = 25
权重_中文占比 = 25
权重_乱码率 = 20
权重_重复率 = 15
权重_标点密度 = 15

阈值_及格总分 = 60.0
硬伤_乱码率 = 0.30       # 超过直接判无效
硬伤_中文占比 = 0.30     # 低于直接判无效

阈值_长度 = 500          # 正常章节净字符下限
阈值_短章长度 = 200      # 短章 (如"作者的话") 净字符下限
阈值_中文占比 = 0.60
阈值_乱码率 = 0.05
阈值_重复率 = 0.40
标点密度下限 = 0.02
标点密度上限 = 0.25

_CJK_RE = re.compile(r'[\u4e00-\u9fff\u3400-\u4dbf]')
# 乱码字符: Unicode 替换符 + 常见乱码区 (私用区/兼容区) + 连续异常符号
_乱码字符_RE = re.compile(r'[\ufffd\ue000-\uf8ff\ufff0-\uffff]')
# 中英文标点集合 (显式列出, 避免引号转义问题)
_PUNCT_CHARS = ('，。！？；：、…—·,!?;:~()（）[]【】《》.-'
                '\u201c\u201d\u2018\u2019"' "'")
_标点_RE = re.compile('[' + re.escape(_PUNCT_CHARS) + ']')
# 连续异常符号串 (4 个以上非常见字符, 视为乱码噪声)
_连续异常串_RE = re.compile(
    '[^\\u4e00-\\u9fff\\u3400-\\u4dbfa-zA-Z0-9\\s' +
    re.escape(_PUNCT_CHARS) + ']{4,}')


@dataclass
class 质检报告:
    """单章内容的质检结果"""
    章节: str = ''
    得分: float = 0.0                     # 0-100
    有效: bool = False
    统计: Dict = field(default_factory=dict)
    原因: List[str] = field(default_factory=list)
    # 清洗统计 (2026-09-29 可观测性): 由爬虫._fetch_with_qc 从 contextvar 读取
    # clean_content 的删除计数后附加, {关键词行,推广行,过短行,符号行,广告行,水印,原始行数}
    清洗统计: Dict = field(default_factory=dict)
    # 2026-10-17 (C6/P1): 疑似过度清洗告警文案 ('' = 无异常)。
    # **只告警不扣分**: 清洗规则误杀是"规则失效"信号, 不是"这一章质量差";
    # 若让它影响 得分/有效, 误报会直接把正常章节判成质检失败 (反弹到重试),
    # 与 P1 "避免误报影响自动判定"的定调冲突。故独立成字段, 由展示层消费。
    疑似过度清洗: str = ''
    # 2026-10-17 (C6/P4): LLM 复核建议文案 ('' = 未送或未启用)。
    # 同样**只告警不改判**: 默认关闭, 仅质检未通过且用户显式启用时才送 LLM
    # 判定"乱码/广告/正文" (见 LLM质检.py); 结论仅供人工复核, 不影响得分/有效。
    LLM建议: str = ''

    def 摘要(self) -> str:
        """一行式摘要 (用于日志/汇总报告)"""
        if self.有效:
            return f"{self.章节} 得分{self.得分:.0f} 通过"
        原因 = '; '.join(self.原因) if self.原因 else '综合得分不足'
        return f"{self.章节} 得分{self.得分:.0f} 失败({原因})"


class 内容质检器:
    """章节正文语义质检 (无状态, 线程安全)"""

    def 质检(self, text: str, 章节标题: str = '') -> 质检报告:
        """对清洗后的正文做五维评分。

        Args:
            text: 清洗后的章节正文
            章节标题: 章节名 (仅用于报告展示)

        Returns:
            质检报告
        """
        报告 = 质检报告(章节=章节标题 or '未命名章节')
        # Rust 加速路径: 返回字段与纯 Python 完全一致; 异常/缺失时回退
        if _RUST_质检可用:
            try:
                _rs = _rs_质检_full(text)
                报告.得分 = _rs['得分']
                报告.有效 = _rs['有效']
                报告.原因 = list(_rs['原因'])
                报告.统计 = dict(_rs['统计'])
                return 报告
            except Exception:
                pass  # Rust 异常 → 回退纯 Python 实现
        if not text or not text.strip():
            报告.原因.append('正文为空')
            报告.统计 = self._空统计()
            return 报告

        统计 = self._统计(text)
        报告.统计 = 统计

        # ---- 单项评分 ----
        得分长度 = self._评分_长度(统计)
        得分中文 = self._评分_中文占比(统计)
        得分乱码 = self._评分_乱码率(统计)
        得分重复 = self._评分_重复率(统计)
        得分标点 = self._评分_标点密度(统计)

        报告.得分 = round(得分长度 + 得分中文 + 得分乱码 + 得分重复 + 得分标点, 1)

        # ---- 硬伤判定 (单项严重超标直接无效, 不看总分) ----
        if 统计['乱码率'] > 硬伤_乱码率:
            报告.原因.append(f"乱码率{统计['乱码率']*100:.0f}%>{硬伤_乱码率*100:.0f}%")
        if 统计['中文占比'] < 硬伤_中文占比:
            报告.原因.append(f"中文占比{统计['中文占比']*100:.0f}%<{硬伤_中文占比*100:.0f}%")

        # ---- 未达阈值的扣分项记录原因 ----
        if 得分长度 == 0 and not 报告.原因:
            报告.原因.append(f"长度不足({统计['净字符数']}字)")
        if 得分中文 == 0 and 硬伤_中文占比 <= 统计['中文占比'] and not 报告.原因:
            报告.原因.append(f"中文占比{统计['中文占比']*100:.0f}%")
        if 得分乱码 == 0 and 统计['乱码率'] <= 硬伤_乱码率:
            报告.原因.append(f"乱码率{统计['乱码率']*100:.0f}%")
        if 得分重复 == 0:
            报告.原因.append(f"重复率{统计['重复率']*100:.0f}%")
        if 得分标点 == 0:
            密度 = 统计['标点密度']
            报告.原因.append(f"标点密度{密度*100:.1f}%")

        报告.有效 = (报告.得分 >= 阈值_及格总分 and not 报告.原因)
        # 修复(U13): 此处原有
        #     if not 报告.有效 and 报告.得分 >= 阈值_及格总分 and not 报告.原因:
        #         报告.原因.append('综合得分不足')
        # 该条件自相矛盾 (得分达标且无原因时 有效 必为 True), 是永不执行的死分支;
        # 且属于冗余 —— 展示层 质检报告.摘要() 已在 原因 为空时兜底输出
        # "综合得分不足"。删除后行为完全不变, 并与 Rust 实现 (lib.rs 质检_core,
        # 结尾同样只算 有效 不补原因) 保持严格镜像 (测试/test_offline_parsing.py
        # 的 TestRustFallbackParity 断言两路的 原因 必须一致)。
        return 报告

    # ------------------------------------------------------------------
    def _统计(self, text: str) -> Dict:
        """计算全部统计指标"""
        lines = [l.strip() for l in text.split('\n') if l.strip()]
        总字符 = len(text)
        cjk数 = len(_CJK_RE.findall(text))
        乱码字符数 = len(_乱码字符_RE.findall(text))
        乱码串数 = len(''.join(_连续异常串_RE.findall(text)))
        标点数 = len(_标点_RE.findall(text))

        行数 = len(lines)
        去重行数 = len(set(lines))

        return {
            '净字符数': 总字符,
            '行数': 行数,
            '中文占比': (cjk数 / 总字符) if 总字符 else 0.0,
            '乱码率': ((乱码字符数 + 乱码串数) / 总字符) if 总字符 else 1.0,
            '重复率': (1 - 去重行数 / 行数) if 行数 else 1.0,
            '标点密度': (标点数 / 总字符) if 总字符 else 0.0,
            '空白行比': ((text.count('\n') + 1 - 行数) / (text.count('\n') + 1))
                        if text.count('\n') else 0.0,
        }

    def _空统计(self) -> Dict:
        return {'净字符数': 0, '行数': 0, '中文占比': 0.0, '乱码率': 1.0,
                '重复率': 1.0, '标点密度': 0.0, '空白行比': 0.0}

    # ------------------------------------------------------------------
    def _评分_长度(self, 统计) -> float:
        长度 = 统计['净字符数']
        if 长度 >= 阈值_长度:
            return 权重_长度
        if 长度 >= 阈值_短章长度:
            # 短章区间按比例给分
            return round(权重_长度 * (长度 - 阈值_短章长度) /
                        (阈值_长度 - 阈值_短章长度), 1)
        return 0.0

    def _评分_中文占比(self, 统计) -> float:
        占比 = 统计['中文占比']
        if 占比 >= 阈值_中文占比:
            return 权重_中文占比
        if 占比 >= 硬伤_中文占比:
            # 30%-60% 区间线性给分
            return round(权重_中文占比 * (占比 - 硬伤_中文占比) /
                        (阈值_中文占比 - 硬伤_中文占比), 1)
        return 0.0

    def _评分_乱码率(self, 统计) -> float:
        率 = 统计['乱码率']
        if 率 <= 阈值_乱码率:
            return 权重_乱码率
        if 率 <= 硬伤_乱码率:
            # 5%-30% 区间线性衰减
            return round(权重_乱码率 * (硬伤_乱码率 - 率) /
                        (硬伤_乱码率 - 阈值_乱码率), 1)
        return 0.0

    def _评分_重复率(self, 统计) -> float:
        率 = 统计['重复率']
        if 率 <= 阈值_重复率:
            return 权重_重复率
        return 0.0

    def _评分_标点密度(self, 统计) -> float:
        密度 = 统计['标点密度']
        if 标点密度下限 <= 密度 <= 标点密度上限:
            return 权重_标点密度
        # 轻微越界给一半分, 严重越界 (纯噪声或纯乱码) 0 分
        if 0.005 <= 密度 < 标点密度下限:
            return round(权重_标点密度 * 0.5, 1)
        if 标点密度上限 < 密度 <= 0.40:
            return round(权重_标点密度 * 0.5, 1)
        return 0.0


