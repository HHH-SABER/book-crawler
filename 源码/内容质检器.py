# ============================================================
# 过度清洗告警 (2026-10-17 · C6 Roadmap P1 半程 A)
# ============================================================
# P1 定调 (文档/实施计划.md): "清洗统计纳入评分语义 —— 删除行占比异常
# (如 >30%) 时质检报告加'疑似过度清洗'标记 (**只告警不扣分**, 避免误报
# 影响自动判定)"。
#
# 为什么需要它: 清洗规则是按"内容特征"删行的 (关键词/推广/过短/符号/广告),
# 站点改版或规则失效时会**成片误杀正文**。误杀不报错、不抛异常, 只会让
# 章节变短 —— 以往唯一的信号是质检低分, 但低分有无数种原因, 分不清
# "站点挂了"还是"清洗规则在杀正文"。本函数给出可区分的信号。
#
# 口径 (与 爬虫.clean_content 的统计严格对应):
#   · 分子 = 5 个**行级**删除计数之和 (关键词行/推广行/过短行/符号行/广告行);
#   · 分母 = 原始行数 (**非空行** —— 空行不参与删除判定, 计入会稀释占比);
#   · 水印是**字符级**替换计数 (re.subn 的次数), 不是行, 不计入分子。
_过度清洗_行级键 = ('关键词行', '推广行', '过短行', '符号行', '广告行')


def 判定过度清洗(清洗统计: Dict, 阈值: float = 0.30,
                 最小样本: int = 10) -> str:
    """删除行占比是否异常 (C6/P1)。返回告警文案; 正常返回 ''。

    只告警不扣分 —— 调用方把它写进 质检报告.疑似过度清洗, **不得**据此改
    得分/有效 (见 P1 定调)。

    Args:
        清洗统计: clean_content 产出的统计 dict (含 原始行数; 缺键按 0 处理,
            容忍旧数据/未接线的调用方)
        阈值: 占比阈值, 默认 0.30 (Roadmap 建议值)
        最小样本: 原始行数少于此值不判定 —— 短章节删 1 行就超阈
            (3 行删 1 行 = 33%), 那是噪声不是信号

    Returns:
        告警文案 (含各维度拆分, 便于定位是哪类规则在杀); '' 表示无异常
    """
    if not isinstance(清洗统计, dict):
        return ''
    try:
        原行 = int(清洗统计.get('原始行数', 0) or 0)
    except (TypeError, ValueError):
        return ''
    if 原行 < 最小样本:
        return ''
    删行 = 0
    明细 = []
    for 键 in _过度清洗_行级键:
        try:
            n = int(清洗统计.get(键, 0) or 0)
        except (TypeError, ValueError):
            n = 0
        if n > 0:
            删行 += n
            明细.append(f'{键}{n}')
    if 删行 <= 0:
        return ''
    占比 = 删行 / 原行
    if 占比 <= 阈值:
        return ''
    return (f'疑似过度清洗: 删除 {删行}/{原行} 行 '
            f'({占比:.0%} > {阈值:.0%}) [{", ".join(明细)}] '
            f'—— 请核对是站点改版还是清洗规则误杀正文')
