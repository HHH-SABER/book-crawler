# -*- coding: utf-8 -*-
"""章节「数据文件模式」的纯逻辑（Wave2 第二块，2026-10-24）。

有些站点把正文放在独立数据文件里（码点流/自定义扩展名），正文页本身只是"加载中"占位。
`爬虫.py::get_chapter_content` 里有一段探测→解码→整理的逻辑，其中**两处细节最容易出错**：

1. **首行元信息的剥离**：数据文件常以"第N章 标题 / 作者：… 字数：…"开头，直接当正文会污染内容；
   而剥离条件（`作者/★/☆/第`）写错就会把正文首段当标题删掉。
2. **复合指纹**：分页的开头常有固定模板，只用"前若干字符"判重会把下一页误判成"已到末页"，
   所以原实现用 `前200字符 + 总长度` 的 sha256 复合指纹。

这两处都是纯函数，抽出来后可离线钉住；编排（读实例状态、break/continue、日志）仍留在 `爬虫.py`，
解码调用也留在原处 —— 避免改变原有的异常/日志行为。
"""
import hashlib


def 整理数据正文(文本: str) -> str:
    """把解码出的数据文本整理成正文：逐行 strip → 去空行 → 剥首行元信息 → 去统计行。

    与原实现逐字一致：
    - 首行含 `作者` / `★` / `☆` / `第` ⇒ 视为标题行丢掉；
    - 同时含 `作者` 与 `字数` 的行、或以 `字数` 开头的行 ⇒ 丢掉（站点统计行）。
    """
    if not 文本:
        return ''
    行s = [行.strip() for 行 in 文本.split('\n') if 行.strip()]
    if 行s and ('作者' in 行s[0] or '★' in 行s[0] or '☆' in 行s[0] or '第' in 行s[0]):
        行s = 行s[1:]
    行s = [行 for 行 in 行s
           if not (('作者' in 行 and '字数' in 行) or 行.startswith('字数'))]
    return '\n'.join(行s)


def 页指纹(正文: str) -> str:
    """复合指纹：`前200字符 + '|' + 总长度` 的 sha256 前 16 位。

    为什么不用整篇哈希：分页正文之间本就有差异；而**固定模板**（页首/页尾导航）会让"只看开头"
    的简单判重误杀。复合指纹在"开头相同但长度不同"时仍能区分。
    """
    正文 = 正文 or ''
    return hashlib.sha256((正文[:200] + f'|{len(正文)}').encode('utf-8')).hexdigest()[:16]
