# -*- coding: utf-8 -*-
"""布局档位 — 响应式断点的**唯一真值来源** (纯函数, 不依赖 Flet / 页面)。

背景 (Phase 4 批 4, 2026-10-07): 程序此前只有"单档 1200px 布尔", 而设计稿
(`界面设计预览/index.html`) 定义了多档断点。用户 2026-10-07 拍板**对齐设计稿**,
并明确: 由于程序窗口 `min_width=960`, ≤720/≤480 两档在桌面端**永远触发不到**,
只作"不崩坏"验证 → 本模块只落**实机能到达**的档位。

设计稿依据 (逐条对应 index.html 的 @media):
  `>1100px`   基准档   —— 侧栏 220 / 抽屉 320 / 统计卡 5 列 / 表格 910px + 横滚
  `≤1100px`   中档     —— 主内容 padding/gap 20 → 16
  `≤960px`    窄档     —— 抽屉 280 / 统计卡 5→3 列 / 日志展开限高 400 → 260
  `≤720/480`  实机不可达 (min_width=960), 不实现
  ⚠️ 设计稿在**任何**断点都**不隐藏任务表列**(固定 910px + 横向滚动) ——
     程序旧策略(≤1200 隐藏 4 个次级列压到 606px)已被用户 2026-10-07 明确改掉。

本模块只回答"给定宽度是哪一档、该档的参数是多少", **不含任何控件** ——
这样它可以被离线用例直接钉死 (响应式此前**零自动化护栏**)。
"""
import re
from pathlib import Path

# 档位名 (对外只用这三个)
宽 = '宽'
中 = '中'
窄 = '窄'

# 阈值取自设计稿 @media (max-width: Npx)。改设计稿就要改这里 ——
# 测试/test_布局档位.py 会**直接读 index.html 的 @media 数值**来交叉校验。
中档阈值 = 1100
窄档阈值 = 960

# 实机不可达说明: 窗口 min_width = 960 (gui_app.py) + 设计稿自己的注记
# (index.html:2300「实机约束: Flet 窗口 min_width=960、min_height=640」)
实机最小宽 = 960

# 档位 → 参数。数值逐条出自设计稿的对应 @media。
_档位参数 = {
    宽: {
        '抽屉宽': 320,          # .detail-drawer width:320px
        '统计列数': 5,          # .stats-row repeat(5,1fr)
        '内容间距': 20,         # .main-content padding/gap: var(--sp-5)=20px
        '日志展开高': 400,      # .log-body.expanded max-height:400px
        '日志基础高': 160,      # .log-body max-height:160px
        '表格固定宽': 910,      # .task-table-inner width:910px (任何档都不变)
        '隐藏次级列': False,    # ⚠️ 设计稿任何断点都不隐藏列
    },
    中: {
        '抽屉宽': 320,          # ≤1100 档侧栏/抽屉**不变** (设计稿只改主内容内距)
        '统计列数': 5,
        '内容间距': 16,         # var(--sp-4)=16px
        '日志展开高': 400,
        '日志基础高': 160,
        '表格固定宽': 910,
        '隐藏次级列': False,
    },
    窄: {
        '抽屉宽': 280,          # ≤960 档 .detail-drawer width:280px
        '统计列数': 3,          # .stats-row repeat(3,1fr)
        '内容间距': 16,         # 设计稿 ≤960 未再改主内容内距 (≤720 才改 12)
        '日志展开高': 260,      # .log-body.expanded max-height:260px
        '日志基础高': 160,
        '表格固定宽': 910,
        '隐藏次级列': False,
    },
}


# 进程内"当前档位" —— gui_app 在 resize 时写入; 页面**构建时**读它取初始参数,
# 这样就不依赖"页面先建还是回调先跑"的顺序 (旧实现靠初始 _窄档=False 蒙)。
# 默认基准档: 首帧 page.width 未就绪时, 宁可先按宽档画 —— 先画窄再放宽,
# 比"先画宽再挤窄"在视觉上更不容易被当成闪烁。
_当前 = [宽]


def 当前档() -> str:
    """当前档位 (未设置过 = 基准档)。"""
    return _当前[0]


def 设置当前档(档: str) -> bool:
    """写入当前档位; 返回**是否真的变了** (幂等, 供调用方决定要不要重排)。"""
    if 档 not in _档位参数:
        档 = 宽
    if 档 == _当前[0]:
        return False
    _当前[0] = 档
    return True


def 计算档位(宽度: int) -> str:
    """按窗口**逻辑**宽度返回档位名 (窄 / 中 / 宽)。

    ⚠️ 传进来的必须是 `page.width` (Flet 的**逻辑**像素), 不是 Win32 物理像素 ——
    本机 DPI 150%, 物理 2250 对应逻辑 1265 (详见 文档/踩坑总表.md K47)。
    """
    # ⚠️ 形参不能叫 宽 —— 会遮蔽同名的档位常量 (本模块最初的写法就踩了,
    # 被测试/test_布局档位.py 当场抓出: 宽档判定恒返回入参宽度而不是档位名)。
    try:
        宽度 = int(宽度 or 0)
    except (TypeError, ValueError):
        return 宽
    if 宽度 <= 0:
        return 宽            # 首帧 page.width 未就绪 → 当成基准档, 别乱切
    if 宽度 <= 窄档阈值:
        return 窄
    if 宽度 <= 中档阈值:
        return 中
    return 宽


def 取参数(档: str = '') -> dict:
    """取该档的参数表 (未知档位回落基准档)。"""
    return dict(_档位参数.get(档) or _档位参数[宽])


def 取参数_按宽(宽度: int) -> dict:
    """一步到位: 宽度 → 参数表。"""
    return 取参数(计算档位(宽度))


def 档位说明(档: str) -> str:
    """日志用的人话描述 (便于从 EXE 日志反查档位是否真生效)。"""
    p = 取参数(档)
    return (f'{档}档 (抽屉{p["抽屉宽"]}px, 统计{p["统计列数"]}列, '
            f'内容间距{p["内容间距"]}px, 日志展开≤{p["日志展开高"]}px)')


# ---------------------------------------------------------------- 设计稿交叉校验
def 读取设计稿断点() -> list:
    """从设计稿 index.html 抽出所有**宽度**断点 (升序), 供用例交叉校验。

    读的是真实设计稿文件, 不是副本 —— 设计稿改了断点而代码没跟, 用例就会红。
    """
    根 = Path(__file__).resolve().parents[2]          # 源码/gui_components → 项目根
    页 = 根 / '界面设计预览' / 'index.html'
    try:
        文本 = 页.read_text(encoding='utf-8')
    except OSError:
        return []
    断点 = {int(m) for m in re.findall(r'@media\s*\(max-width:\s*(\d+)px\)', 文本)}
    return sorted(断点)
